"""Refresh the generated header of `agent-briefing.md`.

MEASURED 2026-10-31 (operator-docs audit): the `/update` command
specification says stage (g) is

    Update timestamp + knowledge count in agent-briefing.md — static
    sections PRESERVED, never overwritten.

and `AGENTS.md` §11 says the same: "/update pipeline: ... rebuild
`agent-briefing.md`". No code did it. `agent-briefing.md` was maintained by
hand, and its "Last updated" line read 2026-10-29 -- two days stale at the
time of the audit -- while the corpus it describes was being regenerated
underneath it. An agent that reads a stale briefing reasons from a corpus
that no longer exists, and the two are never reconciled because nothing
compares them.

So the briefing has two halves:

  * the GENERATED header -- the timestamp and the knowledge counts. This
    module rewrites it, and ONLY it.
  * the STATIC body -- the operating identity, the mission, the startup
    discipline, the learned biases. Hand-maintained, and preserved byte
    for byte.

The counts come from the CANONICAL store, so the briefing cannot claim a
knowledge base the database does not have. If the store cannot be opened,
the briefing is NOT touched: a briefing that says "0 lessons" because the
database was briefly unavailable is worse than a stale one, because it
looks current.

The learned-biases section (the numbered list in the briefing) is also
generated -- it is derived from `memory/report-lessons.md` and
`memory/patterns.md`, which are themselves generated from the canonical
store. It is regenerated by `render_biases()` and spliced between the
`<!-- BEGIN BIASES -->` / `<!-- END BIASES -->` markers when they are
present. A briefing with no markers is left alone in that region, because
guessing where the section starts would corrupt a hand-maintained file.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

BRIEFING = ROOT / "agent-briefing.md"

BEGIN_BIASES = "<!-- BEGIN BIASES -->"
END_BIASES = "<!-- END BIASES -->"

# The two header lines the spec names. Each is rewritten in place; the rest
# of the file is untouched.
_LAST_UPDATED = re.compile(r"^Last updated:.*$", re.MULTILINE)
_KNOWLEDGE = re.compile(r"^Knowledge base:.*$", re.MULTILINE)


def knowledge_counts() -> dict[str, Any]:
    """The counts the briefing reports, read from the canonical store.

    Returns `{"ok": False, ...}` when the store cannot be read, so the
    caller can leave the briefing untouched rather than writing zeros.

    MEASURED 2026-10-31: this opened the store through `orch.store
    .open_db()`, which takes the SCHEMA MIGRATION LOCK. Reading six row
    counts therefore blocked behind any concurrent migration -- and worse,
    it took a lock it did not need, so the briefing refresh and the
    migration it was reporting on could not run at the same time.

    The counts are a pure READ, so they use `wks.readonly.ro()`, which
    opens the live database `mode=ro` with no lock at all. A read cannot
    race with a migration in a way that matters: SQLite's WAL gives the
    reader a consistent snapshot.

    The consequence is that the briefing refresh works WHILE a migration is
    running, instead of timing out after 60 seconds and leaving the
    briefing stale -- which is the exact failure the refresh exists to
    fix.
    """
    try:
        from wks import readonly
        con = readonly.ro()
    except Exception as e:  # noqa: BLE001 - any failure means "do not write"
        return {"ok": False, "reason": f"canonical store unavailable: {e}"}
    try:
        def count(table: str) -> int:
            try:
                return con.execute(
                    f"SELECT count(*) n FROM {table}").fetchone()["n"]
            except Exception:
                return 0

        items = count("item")
        active = 0
        try:
            active = con.execute(
                "SELECT count(*) n FROM item WHERE status='active'"
            ).fetchone()["n"]
        except Exception:
            pass
        skills = len(json.loads(
            (ROOT / "runtime" / "registry.json").read_text(encoding="utf-8")
        ).get("skills", []))
        # LESSONS counted the way `memory/report-lessons.md` counts them:
        # only lessons whose state has advanced past `captured`. A `captured`
        # lesson is an UNVERIFIED claim, and `AGENTS.md` §11 says
        # `memory/report-lessons.md` must not be polluted with unverified
        # material.
        #
        # MEASURED 2026-10-31: the briefing counted EVERY row in `lesson`
        # (10) while the projection it points at reported "0 lessons from
        # the canonical store" -- the same store, the same rows, two
        # different rules. The briefing therefore advertised 10 lessons
        # that no reader of the projection could find. Both now count the
        # lessons that are actually published.
        lessons = 0
        captured = 0
        try:
            lessons = con.execute(
                "SELECT count(*) n FROM lesson WHERE state != 'captured'"
            ).fetchone()["n"]
            captured = con.execute(
                "SELECT count(*) n FROM lesson WHERE state = 'captured'"
            ).fetchone()["n"]
        except Exception:
            pass
        return {
            "ok": True,
            "items": items,
            "active_items": active,
            "lessons": lessons,
            "captured_lessons": captured,
            "verified_lessons": lessons,
            "sources": count("source"),
            "chains": count("chain"),
            "skills": skills,
            "classes": count("bug_class"),
        }
    finally:
        try:
            con.close()
        except Exception:
            pass


def render_header(counts: dict[str, Any]) -> tuple[str, str]:
    """The two header lines, rendered from the counts."""
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    updated = f"Last updated: {stamp}"
    knowledge = (
        f"Knowledge base: WKS domains + learning_engine (SQLite) — "
        f"regenerated by /update — "
        f"{counts['items']} items ({counts['active_items']} active), "
        f"{counts['lessons']} lessons, {counts['sources']} sources, "
        f"{counts['chains']} chains, {counts['classes']} classes, "
        f"{counts['skills']} skills"
    )
    # A captured lesson is an unverified claim and is NOT published in
    # `memory/report-lessons.md`. Saying so keeps the header honest: a
    # reader who finds 0 published lessons can see why.
    if counts.get("captured_lessons"):
        knowledge += (f" ({counts['captured_lessons']} more lessons captured "
                      f"but not yet verified)")
    return updated, knowledge


def render_biases() -> str:
    """The learned-biases block, rendered from the generated memory files.

    `memory/report-lessons.md` and `memory/patterns.md` are themselves
    generated from the canonical store, so the briefing's biases are a
    projection of the corpus, not a hand-typed list that can drift from it.
    """
    lines: list[str] = [BEGIN_BIASES, ""]
    lines.append("_Regenerated from `memory/report-lessons.md` + "
                 "`memory/patterns.md`._")
    lines.append("")
    for name, label in (("memory/report-lessons.md", "Report lessons"),
                        ("memory/patterns.md", "Patterns")):
        path = ROOT / name
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        bullets = [ln.strip() for ln in text.splitlines()
                   if ln.strip().startswith(("- ", "* "))]
        if not bullets:
            continue
        lines.append(f"**{label}**")
        lines.append("")
        for b in bullets[:20]:
            lines.append(f"- {b.lstrip('-* ').strip()}")
        lines.append("")
    lines.append(END_BIASES)
    return "\n".join(lines)


def refresh(*, apply: bool = False) -> dict[str, Any]:
    """Rewrite the generated header. Returns a report.

    `apply=False` reports what WOULD change and writes nothing.
    """
    if not BRIEFING.is_file():
        return {"ok": False, "reason": f"no briefing at {BRIEFING}"}
    counts = knowledge_counts()
    if not counts.get("ok"):
        return {"ok": False, "reason": counts.get("reason"),
                "written": False}
    text = BRIEFING.read_text(encoding="utf-8")
    updated, knowledge = render_header(counts)

    new = text
    if _LAST_UPDATED.search(new):
        new = _LAST_UPDATED.sub(updated, new, count=1)
    else:
        # The line is missing entirely: put it after the title rather than
        # leaving the briefing with no timestamp at all.
        lines = new.splitlines()
        insert_at = 1 if lines else 0
        lines.insert(insert_at, updated)
        new = "\n".join(lines)
    if _KNOWLEDGE.search(new):
        new = _KNOWLEDGE.sub(knowledge, new, count=1)
    else:
        lines = new.splitlines()
        insert_at = 2 if len(lines) > 1 else len(lines)
        lines.insert(insert_at, knowledge)
        new = "\n".join(lines)

    biases_changed = False
    if BEGIN_BIASES in new and END_BIASES in new:
        block = render_biases()
        pattern = re.compile(
            re.escape(BEGIN_BIASES) + r".*?" + re.escape(END_BIASES),
            re.DOTALL)
        replaced = pattern.sub(lambda _m: block, new, count=1)
        biases_changed = replaced != new
        new = replaced

    changed = new != text
    if apply and changed:
        BRIEFING.write_text(new, encoding="utf-8")
    return {"ok": True, "changed": changed, "applied": bool(apply and changed),
            "biases_changed": biases_changed, "counts": counts,
            "updated_line": updated, "knowledge_line": knowledge,
            "path": str(BRIEFING)}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="writeups.briefing")
    ap.add_argument("--apply", action="store_true",
                    help="write the refreshed briefing")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)
    out = refresh(apply=a.apply)
    if a.json:
        print(json.dumps(out, indent=2, default=str))
        return 0 if out.get("ok") else 1
    if not out.get("ok"):
        print(f"briefing NOT refreshed: {out.get('reason')}")
        return 1
    print(out["updated_line"])
    print(out["knowledge_line"])
    print(f"changed: {out['changed']}  applied: {out['applied']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
