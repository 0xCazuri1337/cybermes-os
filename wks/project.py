def skill_path_for(con: sqlite3.Connection, class_id: str):
    """Where the skill for `class_id` must live, or None if unroutable."""
    from . import domains as _domains
    try:
        return _domains.class_subdir(class_id, "skills", con) / "SKILL.md"
    except KeyError:
        return None


# The three derived artifacts a class owns, and how each is rendered.
#
# MEASURED 2026-10-31: `drift()` compared ONLY `skills/SKILL.md`, while
# `refresh_class()` writes three files. The two that were not checked went
# stale in the same incident that made the skill stale: the sqli digest still
# read "maturity: planned - 0 items" and its competency page still read
# "Derived from 0 verified items", against 45 active high-confidence items in
# the db. A projection check that watches one of three projections is a check
# that certifies the tree is clean while two thirds of it is wrong.
#
# Each artifact is named with its subdirectory and its renderer, so the three
# are declared once and the checker cannot fall behind the writers.
_PROJECTIONS = (
    ("skills", "SKILL.md", "skill"),
    ("knowledge", "DIGEST.md", "knowledge"),
    ("assessment", "COMPETENCY.md", "assessment"),
)


def _render_projection(con: sqlite3.Connection, kind: str, class_id: str) -> str:
    """Render one derived artifact. Raises on a broken renderer."""
    if kind == "skill":
        from . import skillgen
        return skillgen.render(con, class_id)
    if kind == "knowledge":
        from . import pipeline
        return pipeline.markdown_report(con, class_id)
    if kind == "assessment":
        from . import methodgen
        return methodgen.render(con, class_id)
    raise KeyError(f"unknown projection kind: {kind!r}")


def drift(con: sqlite3.Connection) -> list[dict[str, Any]]:
    """Classes whose derived artifacts no longer match the corpus.

    Every artifact a class owns is checked -- the skill, the digest and the
    competency page -- because `refresh_class` writes all three and a
    projection check that watches only one of them certifies a tree that is
    two-thirds wrong. MEASURED 2026-10-31: the sqli digest and competency
    page both still reported "0 items" against 45 active high-confidence
    items, and neither was flagged, because only SKILL.md was compared.

    Distinct defects, reported distinctly because they need different fixes and
    conflating them is how a broken check reports "0 findings":

      `stale`  — file exists, content differs. The learning loop gained
                 evidence and the projection was never refreshed. This is the
                 failure this module exists to surface.
      `absent` — class HAS gated items but no projection file. Nothing
                 generated it.
      `orphan` — a projection file exists for a class with NO gated items.
                 Fabricated technique prose (I11), or an evidence set that was
                 retracted.
      `unmapped` — the class does not resolve to a domain folder, so it has
                 nowhere to be written. A routing defect, not a projection one.
    """
    found: list[dict[str, Any]] = []
    ids = [r["id"] for r in con.execute(
        "SELECT id FROM bug_class WHERE status!='retired' ORDER BY id")]
    for cid in ids:
        n_items = con.execute(
            "SELECT count(*) FROM item WHERE class_id=? AND status='active'",
            (cid,)).fetchone()[0]
        for subdir, filename, kind in _PROJECTIONS:
            try:
                from . import domains as _domains
                path = _domains.class_subdir(cid, subdir, con) / filename
            except KeyError:
                found.append({"class_id": cid, "kind": "unmapped",
                              "artifact": kind,
                              "detail": "class does not resolve to a domain folder"})
                continue
            if not n_items:
                if path.exists():
                    found.append({"class_id": cid, "kind": "orphan",
                                  "artifact": kind,
                                  "detail": f"{filename} exists for a class with 0 items"})
                continue
            if not path.exists():
                found.append({"class_id": cid, "kind": "absent",
                              "artifact": kind,
                              "detail": f"{n_items} item(s) but no {filename}"})
                continue
            try:
                want = _render_projection(con, kind, cid)
            except Exception as e:  # noqa: BLE001
                found.append({"class_id": cid, "kind": "render_error",
                              "artifact": kind,
                              "detail": f"{type(e).__name__}: {e}"})
                continue
            if path.read_text(encoding="utf-8") != want:
                found.append({"class_id": cid, "kind": "stale",
                              "artifact": kind,
                              "detail": f"{n_items} item(s) on disk differ from render"})
    return found


def main(argv: list[str] | None = None) -> int:
    import argparse
    import json

    from . import domains  # noqa: F401  (import check)

    ap = argparse.ArgumentParser(prog="wks.project")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--class", dest="classes", action="append", default=None)
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)

    con = store.open_db(create=False)
    try:
        if args.check or not args.apply:
            found = drift(con)
            if args.json:
                print(json.dumps(found, indent=2, default=str))
            else:
                if not found:
                    print("skills drift: 0 problem(s)")
                for f in found:
                    print(f"  [{f['kind']:9}] {f['class_id']:16} {f['detail']}")
                if found:
                    print(f"\nskills drift: {len(found)} problem(s). "
                          f"Fix with: python -m wks.cli skills-sync --apply")
            # A silent zero is the failure this check exists to catch, so a
            # non-empty finding list is a non-zero exit (R15's rule).
            return 1 if found else 0
        res = refresh_all(con, classes=args.classes)
        if args.json:
            print(json.dumps(res, indent=2, default=str))
        else:
            print(f"refreshed {res['classes']} class(es); "
                  f"changed: {', '.join(res['changed']) or 'nothing'}")
            for e in res["errors"]:
                print(f"  ERROR {e}")
        return 1 if res["errors"] else 0
    finally:
        con.close()


if __name__ == "__main__":
    raise SystemExit(main())