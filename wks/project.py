"""Refresh every artifact that is DERIVED from the database, in one place.

    python -m wks.cli skills-sync --check     report drift, exit 1 if any
    python -m wks.cli skills-sync --apply     regenerate
    python -m wks.cli skills-sync             dry run: what would change

Why this module exists
----------------------
Three writers project the corpus onto disk and each one owns a different
artifact:

    wks/pipeline.py    write_class_markdown -> <class>/knowledge/DIGEST.md
    wks/skillgen.py    write_skill          -> <class>/skills/SKILL.md
    wks/methodgen.py   generate_all         -> <class>/assessment/COMPETENCY.md

Each is correct alone and each is called from the cycle and from
`orch.executor.do_maintenance`. None of them was reachable from
`wks/ingest.py` — the ONLY writer of the corpus. So a learning session that
ingested new evidence changed the db and left the skills on disk exactly as
they were, until someone happened to run a cycle. Measured: 70 skill files on
disk, zero of them regenerated by ingest, and the only regeneration triggers
were two CRON JOBS THAT WERE PAUSED.

That is the R19 defect in a new place: a correct, tested, uncalled writer.
`domains/**/skills/SKILL.md` is what Hermes actually loads (it is
`skills.external_dirs` in config.yaml), so a stale skill is not a stale
document — it is the agent being handed yesterday's evidence while the
operator reads a corpus that says today.

So this module is the missing call path AND the drift check. Without a check,
"the learning loop improves the skills" is unfalsifiable: nothing compares the
file on disk against the db it claims to project, so drift is invisible until
someone reads a skill by hand.

Order matters, and every intuitive order is the wrong one. Both documents
render `quality.maturity()`, and two of maturity's seven checks are read
directly out of `bug_class` -- `methodology`, written by methodgen, and `skill`,
written by skillgen. Render a document before its own column is set and it
prints its own gap on the very run that satisfied it; the next call renders
something different, so nothing converges and `changed` is never empty.

So the order is: assessment (sets `methodology`) -> skill (sets `skill_path`,
and its own file is stable because it does not read its own column's absence) ->
knowledge. The digest goes LAST even though SKILL.md links to it, because it is
the document that renders both columns in its own gap list.

Failure isolation is load-bearing. Ingest is the corpus boundary: a broken
projection must never roll back or block evidence that already passed the
anti-fabrication gate. Every writer is therefore isolated and reported as an
error string, and the caller decides. A projection that is merely out of date
is repairable; evidence that is rejected because a markdown file failed to
render is not.
"""
from __future__ import annotations

import sqlite3
from pathlib import Path
from typing import Any

from . import config, store


class ProjectionTargetError(RuntimeError):
    """A projection was asked to write somewhere it does not own.

    RAISED, not logged: the failure mode this guards against is silent. See
    `assert_canonical_connection`.
    """


def _connection_path(con: sqlite3.Connection) -> Path | None:
    """The file backing `con`, or None for an in-memory database."""
    for row in con.execute("PRAGMA database_list"):
        if row[1] == "main":
            name = row[2]
            if not name:
                return None
            return Path(name).resolve()
    return None


def assert_canonical_connection(con: sqlite3.Connection) -> None:
    """Refuse to project from a connection that is not the canonical store.

    MEASURED (2026-10-31): `eval/test_learning_hooks.py` registers a bare
    `sqli` class in a THROWAWAY scratch database and calls
    `learning_engine.engine.update_hook(self.con, ...)`. That hook reached
    `project.refresh_class(con, 'sqli')`, which renders the skill from the
    SCRATCH connection -- zero items -- and then writes it to the REAL
    `domains/web/sqli/skills/SKILL.md`, because the output path is resolved
    from `config.root()`, not from the connection.

    The result: the canonical 45-item sqli hunting skill was overwritten with
    an empty "planned" skeleton, and `tools/audit_architecture.py` R7 reported
    the drift as `sqli: stale -- 45 item(s) on disk differ from render`. The
    corpus in `db/wks.db` was never damaged -- only the PROJECTION was -- so
    every check that reads the database passed while the file the agent
    actually loads was empty.

    The invariant this enforces: a projection renders from the canonical store
    and writes under the canonical root, and the two can never be different
    databases. A scratch or sandboxed database therefore cannot project
    anywhere; it must be pointed at a scratch ROOT via `WKS_ROOT`, which is
    what the sandboxing tests already do for the filesystem side.
    """
    want = config.db_path().resolve()
    got = _connection_path(con)
    if got is None:
        raise ProjectionTargetError(
            "projection refused: the connection has no file-backed canonical "
            "database (in-memory). Point WKS_ROOT at a sandbox and open the "
            "database there; an in-memory corpus must never project onto the "
            "real tree.")
    if got != want:
        raise ProjectionTargetError(
            f"projection refused: connection is {got}, canonical store is "
            f"{want}. A projection may only render from the canonical store, "
            f"because it writes to the canonical tree.")


def _class_rel(class_id: str, con: sqlite3.Connection) -> str:
    from . import domains as _d
    return _d.class_rel(class_id, con)


def _domains_subdir(class_id: str, name: str, con: sqlite3.Connection):
    from . import domains as _d
    return _d.class_subdir(class_id, name, con)


def refresh_class(con: sqlite3.Connection, class_id: str,
                  *, knowledge: bool = True, skill: bool = True,
                  assessment: bool = True) -> dict[str, Any]:
    """Refresh one class's derived artifacts. Never raises.

    Returns which artifacts actually changed, so "regenerated 70 documents"
    keeps meaning something: `changed` is a list, not a count of attempts.
    """
    from . import methodgen, pipeline, skillgen

    out: dict[str, Any] = {"class_id": class_id, "changed": [], "errors": []}

    # The guard runs BEFORE any writer so a mismatched connection cannot
    # half-write: an assessment written from a scratch corpus followed by a
    # refused skill would leave the tree in a state neither projection owns.
    # It is reported rather than raised because this function's contract is
    # "Never raises" -- a broken projection must not roll back or block the
    # evidence that already passed the corpus gate (see the module docstring).
    try:
        assert_canonical_connection(con)
    except ProjectionTargetError as e:
        out["errors"].append(str(e))
        return out

    # ORDER IS LOAD-BEARING AND EVERY INTUITIVE ORDER IS WRONG. Measured: a
    # single refresh_class() call did not converge in any of the three orders
    # tried, because BOTH documents render `quality.maturity()`, and maturity has
    # two of its seven checks read straight out of `bug_class`:
    #
    #   `methodology`  <- written by methodgen  (assessment must go FIRST)
    #   `skill`        <- written by skillgen   (skill must go SECOND)
    #
    # Render either document before its own column is set and it prints its own
    # gap on the run that just satisfied it ("missing: ... skill"); the next call
    # then renders something different, so nothing ever converges and every
    # consumer reads the projection as perpetually dirty. Only after BOTH
    # columns are written is the rendered output stable -- which is why the
    # digest is LAST, not first, even though SKILL.md links to it.
    if assessment:
        try:
            # Compare first, then write -- the same idempotency contract the
            # other two writers honour. Calling methodgen.main() and ASSUMING it
            # changed something made every call report `assessment` as changed,
            # so `changed` became a list of ATTEMPTS rather than of actual
            # writes (the T11 defect, one level up).
            adir = _domains_subdir(class_id, "assessment", con)
            path = adir / "COMPETENCY.md"
            want = methodgen.render(con, class_id)
            if not (path.exists() and path.read_text(encoding="utf-8") == want):
                adir.mkdir(parents=True, exist_ok=True)
                path.write_text(want, encoding="utf-8")
                con.execute(
                    "UPDATE bug_class SET methodology=?, last_reviewed=? "
                    "WHERE id=?",
                    (f"{_class_rel(class_id, con)}/assessment/COMPETENCY.md",
                     store.now(), class_id))
                out["changed"].append("assessment")
        except Exception as e:  # noqa: BLE001
            out["errors"].append(f"assessment: {type(e).__name__}: {e}")

    if skill:
        try:
            r = skillgen.write_skill(con, class_id)
            if r.get("changed"):
                out["changed"].append("skill")
        except Exception as e:  # noqa: BLE001
            out["errors"].append(f"skill: {type(e).__name__}: {e}")

    if knowledge:
        try:
            if pipeline.write_class_markdown(con, class_id) is not None:
                out["changed"].append("knowledge")
        except Exception as e:  # noqa: BLE001 - reported, never raised
            out["errors"].append(f"knowledge: {type(e).__name__}: {e}")

    return out


def refresh_all(con: sqlite3.Connection, *, classes: list[str] | None = None,
                skip_empty: bool = True) -> dict[str, Any]:
    """Refresh every class's derived artifacts.

    `skip_empty` mirrors `skillgen.generate_all`: a class with no gated items
    gets no skill. CONTROL I11 makes that a rule, not an optimisation — a
    skill for an unresearched class is fabricated technique prose.
    """
    if classes is None:
        classes = [r["id"] for r in con.execute(
            "SELECT id FROM bug_class WHERE status!='retired' ORDER BY id")]
    results = []
    for cid in classes:
        if skip_empty:
            n = con.execute(
                "SELECT count(*) FROM item WHERE class_id=? AND status='active'",
                (cid,)).fetchone()[0]
            if not n:
                continue
        results.append(refresh_class(con, cid))
    con.commit()
    return {
        "classes": len(results),
        "changed": sorted({c for r in results for c in r["changed"]}),
        "errors": [e for r in results for e in r["errors"]],
        "detail": results,
    }


