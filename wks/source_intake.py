"""Source intake — let a research wave's discoveries OUTLIVE the wave.

THE PROBLEM THIS SOLVES. A research child that reads 40 pages and cites 5 of
them produces evidence for THIS wave only. Its other 35 pages — the ones it
fetched, confirmed live, and did not end up citing — were never written
anywhere, so the next wave re-derives them, re-spends the fetch budget, and
may reach a different conclusion. The corpus was reading 165 URLs out of a
registry that only grew by hand.

THE RULE THAT MAKES IT SAFE. A source a child "found" is an UNVERIFIED CLAIM
about a URL, which is exactly the shape of a fabricated citation. So intake
refuses anything it cannot independently confirm, and it separates two very
different things that are easy to confuse:

  * DISCOVERED — a URL that exists, is fetchable, and carries the class's
    vocabulary. It becomes a `lead`. It is retrievable and quotable, and it
    can never satisfy MIN_PUBLISHER_HOSTS.
  * NORMATIVE — a source that may count toward the corroboration gate. This
    requires the class's own vocabulary markers ON THE PAGE plus a live
    fetch, and it is deliberately conservative.

A child CANNOT self-promote to normative. Promotion is a separate, explicit
`--normative` operation, and even then the entry is stored as a `discovered`
source carrying `role`, so a later reviewer can demote it. What intake must
never do is let a wave widen the gate on its own say-so.

PERSISTENCE. `db/sources.json` is GENERATED by `tools/build_sources.py` from
four upstream registries, and a fifth was missing: this one. Hand-editing
sources.json would be erased by the next build, which is precisely the
"generator and registry disagree" class of bug. Discovered sources live in
`db/discovered_sources.json`, which the builder now merges. That is the whole
point: a wave's findings become part of the retriever for every future wave.

ANTI-FABRICATION, MEASURED. A candidate is refused unless ALL hold:
  1. it fetches with real content (a 200 that returns a JS shell or a
     byte-identical catch-all is refused -- bytes are not content);
  2. the fetched page contains the class's vocabulary markers, so a nav-chrome
     or catch-all page cannot enter the worklist;
  3. it is not a builder host (gitbook/notion/vercel/netlify/... ), which is
     where unmaintained mirrors live;
  4. its publisher ORG is not already saturated for that class.

Run:
    python -m wks.source_intake FILE.json [--apply] [--normative]
    python -m wks.source_intake --list
    python -m wks.source_intake --stats
"""
from __future__ import annotations

import argparse
import json
import re
import sqlite3
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from . import config, store
from .research_sources import ACCESS, TIERS

SCHEMA_VERSION = 1
DISCOVERED_PATH = config.root() / "db" / "discovered_sources.json"

# A page smaller than this is a shell, an error stub, or a redirect notice.
# Measured on this host: `tools/qget.py` already refuses to print under 2000
# chars for the same reason -- a 140-byte error stub must never be cached as
# evidence, because it is indistinguishable from a real page to a size check.
MIN_CONTENT_CHARS = 2000

# Hosts that host user-generated or auto-published content. A page here can be
# excellent (some lead entries are) but it is never a gate publisher: it can be
# edited or deleted by anyone, so it cannot define what a class IS.
BUILDER_EXACT = {
    "app.notion.com", "notion.site", "notion.so", "gitbook.io", "www.gitbook.io",
    "vercel.app", "netlify.app", "readthedocs.io", "pages.dev", "web.app",
    "firebaseapp.com",
}
BUILDER_SUFFIXES = (
    ".gitbook.io", ".notion.site", ".vercel.app", ".netlify.app",
    ".readthedocs.io", ".pages.dev", ".web.app", ".firebaseapp.com",
    ".github.io",
)

# Page text that proves a fetch returned a shell rather than an article.
_SHELL_MARKERS = (
    "enable javascript", "javascript is required", "just a moment",
    "checking your browser", "please enable js", "cf-browser-verification",
    "access denied", "are you a robot", "verifying you are human",
)

_TAG = re.compile(r"<[^>]+>")
_WS = re.compile(r"\s+")


def _now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _host(url: str) -> str:
    from urllib.parse import urlparse
    h = (urlparse(url).hostname or "").lower()
    return h[4:] if h.startswith("www.") else h


def plain_text(html: str) -> str:
    """Readable text, for vocabulary scoring. Not a security boundary."""
    t = _TAG.sub(" ", html)
    for bad in ("&nbsp;", "&amp;", "&lt;", "&gt;", "&quot;", "&#39;", "&mdash;"):
        t = t.replace(bad, " ")
    return _WS.sub(" ", t).strip()


def is_builder_host(host: str) -> bool:
    if host in BUILDER_EXACT:
        return True
    return any(host.endswith(sfx) for sfx in BUILDER_SUFFIXES)


def load() -> dict[str, Any]:
    if DISCOVERED_PATH.exists():
        doc = json.loads(DISCOVERED_PATH.read_text(encoding="utf-8"))
        doc.setdefault("sources", [])
        return doc
    return {
        "schema_version": SCHEMA_VERSION,
        "generated_by": "wks/source_intake.py",
        "note": (
            "Fifth source registry: sources DISCOVERED by research waves. "
            "Merged into db/sources.json by tools/build_sources.py, so a "
            "wave's findings become retrievable for every future wave. "
            "`role` is enforced by wks/quality.py: only `normative` counts "
            "toward MIN_PUBLISHER_HOSTS."
        ),
        "sources": [],
    }


def save(doc: dict[str, Any]) -> None:
    doc["schema_version"] = SCHEMA_VERSION
    doc["generated_by"] = "wks/source_intake.py"
    doc["updated_at"] = _now()
    rows = sorted(doc["sources"], key=lambda e: e["url"])
    doc["sources"] = rows
    DISCOVERED_PATH.parent.mkdir(parents=True, exist_ok=True)
    DISCOVERED_PATH.write_text(
        json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8")


def already_known(url: str) -> bool:
    """True when the URL is in sources.json OR already discovered.

    The same source must not enter the registry twice under two origins; the
    builder merges by URL, but a duplicate here would read as two independent
    confirmations of the same page.
    """
    p = config.root() / "db" / "sources.json"
    if p.exists():
        doc = json.loads(p.read_text(encoding="utf-8"))
        if any(e["url"] == url for e in doc.get("sources", [])):
            return True
    return any(e["url"] == url for e in load()["sources"])


def cited_orgs(con: sqlite3.Connection | None) -> set[str]:
    if con is None:
        return set()
    return {config.publisher_org(r["host"])
            for r in con.execute("SELECT DISTINCT host FROM source")
            if r["host"]}


def class_markers(class_id: str) -> list[str]:
    """Vocabulary that must appear on a page for it to be about this class.

    A 200 with 78KB of navigation chrome is not a thin source, it is an
    unusable one, and shipping it spends a child's whole fetch budget. This is
    the same lesson as the `book.hacktricks.wiki` byte-identical catch-all.

    MEASURED 2026-10-02, and this was too strict: the list held only the
    catalog's MULTI-WORD aliases, so a page with 123 occurrences of "ldap" and
    46 of "channel binding" was refused for lacking the exact phrase "ldap
    injection". The bare class id is always included, because the class name is
    the one term a page about the class is guaranteed to use.
    """
    from . import taxonomy_ext
    out = {class_id.replace("_", " ").lower(), class_id.lower()}
    for cid, _name, _surf, _cwe, _owasp, _ps, aliases, _summary in taxonomy_ext.CATALOG:
        if cid == class_id:
            out |= {a.replace("-", " ").replace("_", " ").lower() for a in aliases}
            out |= {a.lower() for a in aliases}
    return sorted(m for m in out if len(m) > 3)


def score_page(text: str, markers: list[str]) -> tuple[int, list[str]]:
    low = text.lower()
    hits = [m for m in markers if m.lower() in low]
    return len(hits), hits


def _spread(text: str, hits: list[str], buckets: int = 10) -> float:
    """Fraction of page segments containing any class marker.

    Distinguishes a real article (vocabulary spread through the prose) from a
    keyword catch-all (one repeated phrase). Only consulted when the page also
    carries a shell marker, so ordinary pages pay nothing for it.
    """
    if not hits or not text:
        return 0.0
    size = max(1, len(text) // buckets)
    segs = [text[i * size:(i + 1) * size].lower() for i in range(buckets)]
    marked = sum(1 for s in segs if any(h.lower() in s for h in hits))
    return marked / buckets


def _diversity(text: str) -> float:
    """Distinct-word ratio: a real article is high, a keyword echo is tiny."""
    words = re.findall(r"[a-z]{3,}", text.lower())
    if not words:
        return 0.0
    return len(set(words)) / len(words)


def fetch(url: str, timeout: int = 25) -> tuple[int, str]:
    import urllib.request
    req = urllib.request.Request(url, headers={
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                      "AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36",
        "Accept": "text/html,application/xhtml+xml",
    })
    with urllib.request.urlopen(req, timeout=timeout) as r:
        status = r.status
        raw = r.read()
        charset = r.headers.get_content_charset() or "utf-8"
    return status, raw.decode(charset, errors="replace")


def assess(url: str, class_id: str, want_normative: bool,
           con: sqlite3.Connection | None) -> dict[str, Any]:
    """Independently verify one candidate. Returns a verdict, never a guess."""
    host = _host(url)
    org = config.publisher_org(host)
    v: dict[str, Any] = {"url": url, "host": host, "publisher_org": org,
                         "class_id": class_id, "accepted": False}

    if not host:
        v["reason"] = "no host in url"
        return v
    if is_builder_host(host):
        v["reason"] = ("builder/UGC host: editable by anyone, never a gate "
                       "publisher")
        return v
    if already_known(url):
        v["reason"] = "already in the registry"
        v["duplicate"] = True
        return v
    if want_normative and org in cited_orgs(con):
        v["reason"] = f"org {org} already cited corpus-wide: re-citing adds "\
                      "zero corroboration"
        return v

    markers = class_markers(class_id)
    v["markers"] = markers
    try:
        # `fetch()` returns (status, body): unpack the PAIR. Writing
        # `200, fetch(url)` silently binds the whole tuple to `html` and
        # every verdict downstream becomes a TypeError.
        status, html = fetch(url)
    except Exception as exc:                      # noqa: BLE001 - report it
        v["reason"] = f"fetch failed: {type(exc).__name__}: {exc}"
        return v

    v["http_status"] = status
    if status != 200:
        v["reason"] = f"HTTP {status}"
        return v
    v["title"] = _title(html)                    # from the RAW markup
    text = plain_text(html)
    v["content_chars"] = len(text)
    if len(text) < MIN_CONTENT_CHARS:
        v["reason"] = (f"only {len(text)} chars of text: a shell, stub or "
                       "redirect notice, not an article")
        return v
    low = text.lower()
    shell = [m for m in _SHELL_MARKERS if m in low]
    # A shell marker alone is NOT disqualifying. MEASURED: OWASP's own attack
    # pages carry "it is necessary to enable JavaScript" in the site footer
    # while serving 12,396 chars of genuine prose -- refusing on the marker
    # alone would discard a normative source from one of only five normative
    # publisher orgs, which is the opposite of widening coverage. A shell has
    # NO content; a shell marker on a 12KB article is a footer. The size floor
    # above is the real shell test, so markers only refine the verdict.
    if shell and len(text) < 3 * MIN_CONTENT_CHARS:
        v["shell_markers"] = shell
        v["reason"] = (f"bot-wall/shell markers {shell} on a page with only "
                       f"{len(text)} chars: a wall, not an article")
        return v
    v["shell_markers"] = shell

    n, hits = score_page(text, markers)
    v["marker_hits"] = hits
    v["marker_count"] = n
    if n == 0:
        v["reason"] = ("no class vocabulary on the page: nav chrome or a "
                       "catch-all, not a source for this class")
        return v
    # A catch-all page can ECHO the keywords, so a raw hit count is not
    # evidence. Require the vocabulary to be DISTRIBUTED through the prose:
    # a real article mentions each alias in a different region, a keyword
    # blob repeats one phrase and leaves the rest of the page empty.
    if shell:
        spread = _spread(text, hits)
        v["marker_spread"] = spread
        if spread < 0.25:
            v["reason"] = (f"shell markers with keywords bunched in "
                           f"{spread:.0%} of the page: a keyword catch-all, "
                           f"not an article")
            return v
        # Spread is not enough on its own: a blob repeated 200x is spread
        # evenly across its own half of the page. The discriminator is
        # LEXICAL DIVERSITY -- a real article draws on thousands of distinct
        # words, a keyword echo on about ten. Only consulted on the already
        # suspicious path, so a legitimately repetitive OWASP cheat sheet
        # (bulleted, term-dense) is never refused for being repetitive.
        div = _diversity(text)
        v["lexical_diversity"] = round(div, 4)
        if div < 0.05:
            v["reason"] = (f"only {div:.1%} distinct words ({len(text)} chars): "
                           f"a keyword echo or catch-all, not an article")
            return v

    v["accepted"] = True
    v["reason"] = f"live, {len(text)} chars, {n}/{len(markers)} class markers"
    v["access"] = "open"
    v["title"] = _title(text) or f"{class_id} reference"
    return v


def _title(text: str) -> str:
    m = re.search(r"(?i)<title[^>]*>(.*?)</title>", text)
    return m.group(1).strip()[:120] if m else ""


def ingest(candidates: list[dict[str, Any]], want_normative: bool,
           con: sqlite3.Connection | None) -> dict[str, Any]:
    doc = load()
    have = {e["url"] for e in doc["sources"]}
    accepted, refused = [], []
    for c in candidates:
        url = (c.get("url") or "").strip()
        class_id = (c.get("class_id") or c.get("class") or "").strip()
        if not url or not class_id:
            refused.append({"url": url, "class_id": class_id,
                            "reason": "candidate needs url + class_id"})
            continue
        v = assess(url, class_id, want_normative, con)
        if not v["accepted"] or url in have:
            refused.append(v)
            continue
        src_type = c.get("source_type") or ("cheatsheet" if want_normative
                                            else "writeup")
        if src_type not in config.SOURCE_AUTHORITY:
            refused.append({**v, "reason": f"source_type {src_type!r} not in "
                                          "config.SOURCE_AUTHORITY"})
            continue
        entry = {
            "url": url,
            "host": v["host"],
            "publisher_org": v["publisher_org"],
            "publisher_name": c.get("publisher") or v["host"],
            "source_type": src_type,
            "role": "normative" if want_normative else "lead",
            "tier": c.get("tier") or (2 if want_normative else 3),
            "access": v["access"],
            "title": v["title"],
            "note": (c.get("note") or f"Discovered by a research wave for "
                     f"{class_id}; verified live with class vocabulary at "
                     f"intake. Markers: {', '.join(v['marker_hits'])}."),
            "classes": [class_id],
            "defined_in": ["wks.source_intake"],
            "verified": "intake-verified",
            "discovered_at": _now(),
            "content_chars": v["content_chars"],
            "marker_hits": v["marker_hits"],
        }
        if entry["tier"] not in TIERS:
            refused.append({**v, "reason": f"tier {entry['tier']} not in TIERS"})
            continue
        if entry["access"] not in ACCESS:
            refused.append({**v, "reason": f"access {entry['access']} unknown"})
            continue
        doc["sources"].append(entry)
        have.add(url)
        accepted.append(entry)
    return {"doc": doc, "accepted": accepted, "refused": refused}


def stats() -> dict[str, Any]:
    doc = load()
    rows = doc["sources"]
    by_role: dict[str, int] = {}
    for r in rows:
        by_role[r["role"]] = by_role.get(r["role"], 0) + 1
    per_class: dict[str, int] = {}
    for r in rows:
        for c in r.get("classes", []):
            per_class[c] = per_class.get(c, 0) + 1
    return {
        "total": len(rows),
        "by_role": by_role,
        "hosts": len({r["host"] for r in rows}),
        "publisher_orgs": len({r["publisher_org"] for r in rows
                               if r.get("publisher_org")}),
        "classes_covered": len(per_class),
        "per_class": dict(sorted(per_class.items(),
                                 key=lambda kv: (kv[1], kv[0]))),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="source_intake")
    ap.add_argument("file", nargs="?", help="candidates JSON")
    ap.add_argument("--apply", action="store_true",
                    help="write the registry (default is a dry run)")
    ap.add_argument("--normative", action="store_true",
                    help="allow these to count toward MIN_PUBLISHER_HOSTS")
    ap.add_argument("--list", action="store_true", help="print the registry")
    ap.add_argument("--stats", action="store_true", help="coverage summary")
    a = ap.parse_args(argv)

    if a.stats:
        print(json.dumps(stats(), indent=1))
        return 0
    if a.list:
        print(json.dumps(load(), indent=1, ensure_ascii=False))
        return 0
    if not a.file:
        ap.print_help()
        return 2

    p = Path(a.file)
    if not p.exists():
        print(f"no such file: {p}")
        return 2
    payload = json.loads(p.read_text(encoding="utf-8"))
    cands = payload["sources"] if isinstance(payload, dict) else payload
    if not isinstance(cands, list):
        print("expected a list of candidates, or {'sources': [...]}")
        return 2

    con = store.connect(config.DB_PATH) if config.DB_PATH.exists() else None
    try:
        res = ingest(cands, a.normative, con)
    finally:
        if con:
            con.close()

    print(f"candidates={len(cands)} accepted={len(res['accepted'])} "
          f"refused={len(res['refused'])} mode="
          f"{'normative' if a.normative else 'lead'}")
    for e in res["accepted"]:
        print(f"  ACCEPT {e['role']:10s} {e['host']:28s} {e['url']}")
    for r in res["refused"]:
        print(f"  REFUSE {r.get('host') or '-':28s} {r.get('url', '')}")
        print(f"         {r.get('reason')}")

    if a.apply and res["accepted"]:
        save(res["doc"])
        print(f"wrote {DISCOVERED_PATH}")
        print("next: python tools/build_sources.py   "
              "(then --check to prove no drift)")
    elif res["accepted"]:
        print("dry run: pass --apply to persist")
    return 0


if __name__ == "__main__":
    sys.exit(main())
