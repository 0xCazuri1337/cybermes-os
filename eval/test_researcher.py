"""Regression tests for autonomous research (`orch.researcher`).

These cover the failures measured while building the module, each of which
looked like a working system until the specific case was exercised:

  R1  Independence is per REGISTRABLE DOMAIN. `wstg.owasp.org` and
      `cheatsheetseries.owasp.org` are one publisher; counting them as two lets
      a single author satisfy the 2-host rule.
  R2  Over-collapsing is also a failure. An earlier broad suffix list merged
      `cwe.mitre.org` into `mitre.org`, which would reject genuinely independent
      corroboration. Both directions are tested, because only testing the
      strict direction hides the second bug.
  R3  A claim must describe behaviour. The gate accepted "CWE-639: Authorization
      Bypass Through User-Controlled Key" as high-confidence: two publishers,
      a real quote, and not one thing a reader could not get from the class id.
  R4  A span cut mid-sentence is a real substring, so `verify_span` passes it,
      and the gate then rejects the item as unverifiable. Extraction must not
      emit one.
  R5  The evidence key is `host`. The gate counts distinct `host` values; an
      item carrying `publisher` instead looked like it had zero publisher hosts
      and every autogenerated item was rejected with a misleading reason.
  R6  When fewer than two independent publishers answer, the module must
      REFUSE rather than emit a single-source item.

No network. Every case is a fixture, so a suite failure means the logic broke,
not that a publisher was slow.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

PASSES = 0
FAILURES: list[str] = []


def check(name: str, cond: bool, detail: str = "") -> None:
    global PASSES
    if cond:
        PASSES += 1
        print(f"  [PASS] {name}")
    else:
        FAILURES.append(f"{name}: {detail}")
        print(f"  [FAIL] {name}  {detail}")


def main() -> int:  # noqa: C901 - a flat list of independent cases reads better
    from orch.researcher import (candidate_spans, registrable_domain,
                                 verify_span)

    print("R1 independence is per registrable domain, not per host")
    check("two OWASP hosts are one publisher",
          registrable_domain("wstg.owasp.org")
          == registrable_domain("cheatsheetseries.owasp.org"),
          f'{registrable_domain("wstg.owasp.org")} vs '
          f'{registrable_domain("cheatsheetseries.owasp.org")}')
    check("www is stripped before comparing",
          registrable_domain("www.owasp.org") == "owasp.org",
          registrable_domain("www.owasp.org"))
    check("a port does not change identity",
          registrable_domain("owasp.org:443") == "owasp.org",
          registrable_domain("owasp.org:443"))

    print("\nR2 over-collapsing is ALSO a failure (both directions are real)")
    # These are eTLD+1 reductions, which is the CORRECT direction: MITRE
    # publishes both CWE and ATT&CK, so an item citing one and the other is
    # citing one publisher twice. An earlier broad suffix list over-collapsed
    # further; this pins the correct reduction so it cannot regress.
    check("CWE and ATT&CK are one publisher (both MITRE)",
          registrable_domain("cwe.mitre.org")
          == registrable_domain("attack.mitre.org") == "mitre.org",
          f'{registrable_domain("cwe.mitre.org")} vs '
          f'{registrable_domain("attack.mitre.org")}')
    check("NVD reduces to nist.gov",
          registrable_domain("nvd.nist.gov") == "nist.gov",
          registrable_domain("nvd.nist.gov"))
    check("unrelated publishers stay distinct",
          registrable_domain("portswigger.net")
          != registrable_domain("owasp.org"))
    check("github and raw.githubusercontent are distinct voices",
          registrable_domain("github.com")
          != registrable_domain("raw.githubusercontent.com"))

    print("\nR2b a two-part public suffix is handled")
    check("bbc.co.uk and theguardian.co.uk are different",
          registrable_domain("bbc.co.uk")
          != registrable_domain("theguardian.co.uk"))
    check("www.bbc.co.uk normalises to bbc.co.uk",
          registrable_domain("www.bbc.co.uk") == "bbc.co.uk",
          registrable_domain("www.bbc.co.uk"))

    print("\nR3 a claim must describe behaviour, not name a concept")
    title = "CWE-639: Authorization Bypass Through User-Controlled Key (4.20)"
    spans = candidate_spans(title, "idor")
    check("a definition title yields no claim", spans == [], str(spans[:1]))

    prose = ("Cross-site scripting occurs when an attacker uses a web "
             "application to send malicious code to an unsuspecting user.")
    spans = candidate_spans(prose, "xss")
    check("a behavioural sentence IS accepted", len(spans) >= 1, str(spans[:1]))

    print("\nR4 a span must not be cut mid-sentence")
    body = ("The system allows an attacker to read data, e.g. credentials. "
            "Input validation will not always prevent XSS, especially when it "
            "is required to accept user input. The attacker can then read "
            "other users data without permission from the server.")
    spans = candidate_spans(body, "xss")
    for claim, _q in spans:
        check(f"span ends cleanly: {claim[:38]!r}",
              claim.rstrip().endswith((".", "!", "?")), claim[-40:])

    print("\nR5 verify_span does not invent a match")
    page = ("The system's authorization functionality does not prevent one "
            "user from gaining access to another user's data.")
    check("a real span verifies", verify_span(page, page))
    check("whitespace differences still verify",
          verify_span("does  not prevent one user", page))
    check("a fabricated span does NOT verify",
          not verify_span("prevents privilege escalation to root", page))
    # A prefix of the page IS present in the page, so it must verify. Asserting
    # the opposite was a wrong expectation, not a missing guard: what matters
    # is that verification never REPORTS a span the page does not contain.
    check("a genuine prefix DOES verify",
          verify_span(page[:40], page))
    check("a reordered span does NOT verify",
          not verify_span("prevent one user does not functionality "
                          "authorization the system's", page))

    print("\nR6 the module refuses rather than emitting a single source")
    import orch.researcher as R
    saved = R.fetch_source
    try:
        class FakeResult:
            def __init__(self, domain, spans):
                self.domain, self.spans = domain, spans
                self.url, self.source_type = f"https://{domain}/x", "taxonomy"
                self.ok, self.error, self.text = True, "", "text" * 500

        R.fetch_source = lambda url, stype: FakeResult(
            "onlyone.example", [("a real behavioural claim about access "
                                 "control that allows an attacker to read "
                                 "data.", "")][:3])
        out = R.research_class("idor")
        check("one publisher is refused", out.get("items") == [], str(out)[:160])
        check("the refusal explains why",
              "publisher" in str(out.get("error", "")).lower(),
              str(out.get("error")))
    finally:
        R.fetch_source = saved

    print("\nR7 the seed list itself satisfies the independence rule")
    from urllib.parse import urlparse
    from wks import taxonomy
    bad = []
    for seed in taxonomy._SEED:
        doms = {registrable_domain(urlparse(u).netloc) for u, _ in seed.sources}
        if len(doms) < 2:
            bad.append((seed.id, sorted(doms)))
    check("every seed class has >=2 independent publishers", not bad, str(bad))

    print(f"\n{'ALL ' + str(PASSES) + ' CHECKS PASS' if not FAILURES else 'FAILURES'}")
    for f in FAILURES:
        print(f"  FAILED: {f}")
    return 1 if FAILURES else 0


if __name__ == "__main__":
    raise SystemExit(main())
